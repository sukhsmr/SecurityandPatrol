/**
 * Concatenates the site's WordPress/LiteSpeed stylesheets (listed, in load
 * order, in scripts/site-stylesheets.json) into one file, so every page loads
 * 1 stylesheet instead of ~70 render-blocking ones.
 *
 * - Order is preserved exactly, so the cascade (and the design) is unchanged.
 * - The bundle is written to the same folder as the sources, so relative
 *   url()s inside them still resolve.
 * - A few url()s are pointed at local files (see ASSET_REWRITES).
 *
 * Runs before every build (scripts/build.cjs). Run `npm run css:bundle` after
 * changing the manifest or any source stylesheet.
 */
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const cssDir = path.join(root, "public", "wp-content", "litespeed", "css");
const BUNDLE = "site.bundle.css";
const SOURCES = require("./site-stylesheets.json");

// Images still loaded from the old brand's domain whose local copy was
// verified byte-identical; serving them locally removes that dependency.
const OLD_DOMAIN = "https://www.adsguards.com";
const LOCAL_IDENTICAL = [
  "/wp-content/uploads/2023/03/Contruction1-2.jpg.webp",
  "/wp-content/uploads/2023/03/Event-Protection-1024x683-1-1.jpg",
  "/wp-content/uploads/2023/03/High_Rise_OR.jpeg.webp",
  "/wp-content/uploads/2023/03/MOBILE_PATROL-e1753305772866.jpg",
  "/wp-content/uploads/2023/03/Residential-e1753360148140.jpg",
  "/wp-content/uploads/2023/03/Unarmed1-1.jpeg",
  "/wp-content/uploads/2023/03/hero-home-e1678126717789.jpeg",
];

const ASSET_REWRITES = [
  ...LOCAL_IDENTICAL.map((localPath) => [OLD_DOMAIN + localPath, localPath]),
  // Renamed during the rebrand; the stylesheets still used the old name (404).
  // Matched by file name so both absolute and relative url()s are fixed.
  [
    "shopping-center-ads-security-guard-services-mall-corridor.avif",
    "shopping-center-security-and-patrol-security-guard-services-mall-corridor.avif",
  ],
];

let css = "";
for (const file of SOURCES) {
  // Newline between files so a source without a trailing newline cannot merge with the next.
  css += `/* ${file} */\n${fs.readFileSync(path.join(cssDir, file), "utf8")}\n`;
}
for (const [from, to] of ASSET_REWRITES) css = css.split(from).join(to);

fs.writeFileSync(path.join(cssDir, BUNDLE), css);

// The admin's rich text editor and preview render content inside an iframe
// with the website's full styling: the theme bundle plus the app's own CSS
// (which the public site loads through Next.js).
const APP_CSS = ["globals.css", "wordpress-inline.css", "services-inline.css"];
const EDITOR_BUNDLE = "editor.bundle.css";
const editorCss =
  css + APP_CSS.map((file) => `/* src/app/${file} */\n${fs.readFileSync(path.join(root, "src", "app", file), "utf8")}\n`).join("");
fs.writeFileSync(path.join(cssDir, EDITOR_BUNDLE), editorCss);

const version = (text) => crypto.createHash("sha1").update(text).digest("hex").slice(0, 10);
const hash = version(css);
writeIfChanged(
  path.join(root, "src", "components", "site", "siteStylesheet.ts"),
  "// Generated by scripts/bundle-css.cjs. Do not edit.\n" +
    `export const SITE_STYLESHEET = '/wp-content/litespeed/css/${BUNDLE}?v=${hash}';\n` +
    `export const EDITOR_STYLESHEET = '/wp-content/litespeed/css/${EDITOR_BUNDLE}?v=${version(editorCss)}';\n`,
);

writeIfChanged(
  path.join(root, "src", "lib", "cms", "sections", "backgroundDefaults.json"),
  `${JSON.stringify(backgroundDefaults(editorCss), null, 2)}\n`,
);

console.log(`Bundled ${SOURCES.length} stylesheets into ${BUNDLE} (${Math.round(css.length / 1024)} KB, v=${hash})`);

function writeIfChanged(file, contents) {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== contents) fs.writeFileSync(file, contents);
}

/**
 * The background image each Elementor element currently gets from the CSS,
 * as { "<element id>": { desktop, mobile } }. The admin shows these as the
 * defaults of the "Background image" fields; a section only overrides the
 * CSS when an admin picks a different image.
 */
function backgroundDefaults(source) {
  const result = {};
  const toPublicPath = (url) => {
    const clean = url.trim().replace(/^["']|["']$/g, "");
    if (clean.startsWith("data:")) return null;
    if (/^https?:\/\//i.test(clean)) return clean;
    if (clean.startsWith("/")) return clean;
    // Relative to /wp-content/litespeed/css/.
    return new URL(clean, "http://x/wp-content/litespeed/css/").pathname;
  };
  const media = [];
  let i = 0;
  let head = "";
  while (i < source.length) {
    if (source.startsWith("/*", i)) {
      const end = source.indexOf("*/", i + 2);
      i = end < 0 ? source.length : end + 2;
      continue;
    }
    const ch = source[i];
    if (ch === "{") {
      const selector = head.trim();
      head = "";
      if (selector.startsWith("@")) {
        media.push(selector);
        i++;
        continue;
      }
      const end = source.indexOf("}", i);
      const body = source.slice(i + 1, end);
      i = end + 1;
      const bg = /background(?:-image)?\s*:[^;]*url\(([^)]+)\)/i.exec(body);
      if (!bg) continue;
      const url = toPublicPath(bg[1]);
      if (!url) continue;
      const context = media.join(" ");
      const breakpoint = /max-width:\s*7(67|68)px/.test(context) ? "mobile" : /max-width|min-width/.test(context) ? null : "desktop";
      if (!breakpoint) continue;
      // Rules that style the element itself, or (for columns) its direct
      // .elementor-widget-wrap child, which is where Elementor puts column
      // backgrounds. Descendants and overlays are ignored.
      for (const part of selector.split(",")) {
        const match = /elementor-element-([0-9a-f]{6,8})(?::not\([^)]*\))*(\s*>\s*\.elementor-widget-wrap)?\s*$/.exec(part.trim());
        if (!match) continue;
        const entry = (result[match[1]] ??= {});
        entry[breakpoint] = url;
        if (match[2]) entry.target = "widget-wrap";
      }
      continue;
    }
    if (ch === "}") {
      media.pop();
      head = "";
      i++;
      continue;
    }
    head += ch;
    i++;
  }
  return Object.fromEntries(Object.keys(result).sort().map((key) => [key, result[key]]));
}
